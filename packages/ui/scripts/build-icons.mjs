const inner = (name) => {
  const svg = readFileSync(join(root, `${name}.svg`), 'utf8');
  return svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*\/>/, '')
    .replace(/\s+/g, ' ')
    .trim();
};

const entries = new Map();
for (const name of tabler) entries.set(name, inner(name));
for (const [alias, target] of Object.entries(aliases)) entries.set(alias, inner(target));
for (const name of entries.keys())
  if (name.endsWith('-filled')) throw new Error(`Filled icon not allowed: ${name}`);

const body = [...entries]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, markup]) => `  ${JSON.stringify(name)}: ${JSON.stringify(markup)},`)
  .join('\n');
writeFileSync(
  new URL('../src/icons.ts', import.meta.url),
  `// Generated by scripts/build-icons.mjs from @tabler/icons (MIT). Do not edit by hand.\nexport const icons = {\n${body}\n} as const;\nexport type IconName = keyof typeof icons;\n`,
);
console.log(`icons: ${entries.size}`);
